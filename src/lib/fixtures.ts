/* ==========================================================================
 * Savings months, shares and collection
 *
 * Deliberately uneven: one member saving several times a month, one who has
 * saved once, one who has saved nothing at all this month. A collection screen
 * where every row reads the same proves nothing about how it behaves on a bad
 * afternoon. Under open savings none of these is a problem to chase — which is
 * exactly what the screens have to convey.
 * ======================================================================== */

