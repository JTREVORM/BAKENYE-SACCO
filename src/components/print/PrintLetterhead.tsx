import { formatDateTime } from '@/lib/format';

/**
 * The letterhead every printed and saved-to-PDF report carries.
 *
 * Reports are the one place the application produces a document that leaves the
 * building — a member takes a statement to a bank, a manager files a collection
 * report, an auditor keeps a member register. Such a document has to say, on
 * its own, what it is: which SACCO issued it, what it covers, over what period,
 * when it was produced and by whom. A screenshot of a web page does not.
 *
 * It is `hidden` on screen because each page already has its own heading; it
 * appears only in the printed output, where that heading is gone. `print:block`
 * is what makes the same route serve both.
 *
 * There is no PDF library behind this. The browser's own print engine renders
 * it, which on the low-end Android phones most of the membership uses is the
 * difference between a document and a 300 KB download that never finishes.
 */
export function PrintLetterhead({
  title,
  subtitle,
  meta = [],
  generatedBy,
  generatedAt,
}: {
  /** What the document is: "Savings by Category", "Member Register". */
  title: string;
  /** What it is about: the category, the member, the filter applied. */
  subtitle?: string;
  /** Period covered, filters, totals — whatever the reader needs to trust it. */
  meta?: { label: string; value: string }[];
  /** Named on the document, because a financial report needs an author. */
  generatedBy?: string;
  /** Defaults to the moment the page was rendered. */
  generatedAt?: string | Date;
}) {
  const stamped = formatDateTime(generatedAt ?? new Date());

  const lines = [
    ...meta,
    { label: 'Generated', value: stamped },
    ...(generatedBy ? [{ label: 'Generated by', value: generatedBy }] : []),
  ];

  return (
    <header className="print-letterhead mb-5 hidden print:block" aria-hidden="true">
      <div className="flex items-start gap-4 border-b-2 border-black pb-3">
        {/* A plain <img>: this element only ever renders in print, where
            next/image's srcset and lazy loading buy nothing. */}
        {/* eslint-disable-next-line @next/next/no-img-element */}
        <img
          src="/brand/bnd-logo.png"
          alt=""
          width={56}
          height={56}
          className="h-14 w-14 shrink-0 object-contain"
        />

        <div className="min-w-0 flex-1">
          <p className="text-[13pt] font-bold leading-tight tracking-tight">
            BAKENYE UNITY AND DEVELOPMENT SACCO
          </p>
          <p className="text-[9pt] leading-tight">
            Savings and Credit Cooperative Society · Uganda
          </p>
        </div>

        <div className="shrink-0 text-right">
          <p className="text-[12pt] font-bold leading-tight">{title}</p>
          {subtitle ? <p className="text-[9.5pt] leading-tight">{subtitle}</p> : null}
        </div>
      </div>

      <dl className="mt-2 flex flex-wrap gap-x-8 gap-y-1 text-[9pt]">
        {lines.map((line) => (
          <div key={line.label} className="flex gap-1.5">
            <dt className="font-semibold">{line.label}:</dt>
            <dd>{line.value}</dd>
          </div>
        ))}
      </dl>
    </header>
  );
}

/**
 * The closing line of a printed report.
 *
 * States where the figures came from, because a printed total with no
 * provenance is the kind of thing that starts an argument at an AGM.
 */
export function PrintFooter({ note }: { note?: string }) {
  return (
    <footer
      className="print-footer mt-6 hidden border-t border-black/40 pt-2 text-[8.5pt] print:block"
      aria-hidden="true"
    >
      <p>
        {note ??
          'Every figure on this document is computed from the member transaction ledger at the time of printing.'}
      </p>
      <p className="mt-0.5">
        BAKENYE UNITY AND DEVELOPMENT SACCO · system-generated, valid without signature.
      </p>
    </footer>
  );
}
